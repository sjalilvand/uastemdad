$caddyOk = Download-File @(
    "https://caddyserver.com/api/download?os=windows&arch=amd64"
) "$ToolsDir\caddy.exe"
if ($caddyOk -and (Get-Item "$ToolsDir\caddy.exe" -ErrorAction SilentlyContinue).Length -lt 30MB) { $caddyOk = $false }
if (-not $caddyOk) {
    # منبع جایگزین: ریلیز رسمی گیت‌هاب (فایل zip — فایل اجرایی caddy.exe داخل آن است)
    $caddyZip = "$ToolsDir\caddy.zip"
    if (Download-File @(
        "https://github.com/caddyserver/caddy/releases/download/v2.11.9/caddy_2.11.9_windows_amd64.zip"
    ) $caddyZip) {
        try { Expand-Archive -Path $caddyZip -DestinationPath $ToolsDir -Force } catch {}
        if ((Test-Path "$ToolsDir\caddy.exe") -and (Get-Item "$ToolsDir\caddy.exe").Length -gt 30MB) { $caddyOk = $true }
    }
}
if (-not $caddyOk) {
    Write-Host "هشدار: دریافت Caddy ناموفق بود — بعداً این دستور را اجرا کنید: powershell -ExecutionPolicy Bypass -File $App\fix-https.ps1   | دسترسی موقت: http://${ServerIP}:$AppPort" -ForegroundColor Yellow
