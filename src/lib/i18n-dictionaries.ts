export const DICTS: Record<Locale, Record<string, string>> = { fa, en, ar };

/** انتخاب فیلد چندزبانه از رکورد دیتابیس با بازگشت به فارسی */
export function pickLocalized<T extends Record<string, unknown>>(
  item: T,
  base: string,
  locale: Locale
): string {
  if (locale !== "fa") {
    const v = item[`${base}${locale === "en" ? "En" : "Ar"}`];
    if (typeof v === "string" && v.trim()) return v;
  }
  const fb = item[base];
  return typeof fb === "string" ? fb : "";
}
